#include <stdio.h>
/*
# 表示预处理，include 包含
<> 表示系统的路径(前期都使用<>)，使用""表示用户的路径
stdio.h ==> standard input output header 标准输入输出头文件*
*头文件就是别人提前写好的一堆现成的函数的“说明书+声明”
标准输入设备：键盘，标准输出设备：显示器
说明：头文件不是必须的，用到的时候就包含
*/
int main()
// int 表示函数的返回值类型为整型，main是主函数，一个C程序有且只能有一个主函数
// 主函数既是入口也是出口，()是函数的标记，里面可以有参数
{
    // {} 是函数体，也就是函数功能的具体实现部分
    printf("Hello world.\n"); // printf()用于向显示器输出内容
    return 0; // return 表示返回到调用位置，0表示正常返回
}