#include <stdio.h>

/*
for 循环基本语法：
for(表达式1; 表达式2; 表达式3)
{
    循环体;
}

表达式1：只执行一次，通常是初始化循环条件
表达式2：循环条件的判断，决定了循环是否继续
表达式3：循环控制变量的修改，使循环趋于终止（不能是死循环）

执行流程：
先执行表达式1，再判断表达式2，如果成立则执行循环体，
然后再计算表达式3，再接着判断表达式2；
如果表达式2不成立，则退出循环

重点：for 语句中的三个表达式均能省略
（并不是真正意义上的省，其本质只是换了位置），
但有且必须有两个分号！
当条件表达式2省略时，表示永远为真，
此时要在循环中添加退出的条件，否则是死循环！
*/

int main()
{
    int i, sum;

    // 保存和的变量初始化为0，求乘积的初始化为1
    printf("写法1：标准 for 循环，求 1 到 100 的和 \n");
    for(i = 1, sum = 0; i <= 100; i++)
    {
        sum += i;
    }
    printf("%d\n", sum);


    printf("\n 写法2：省略 for 括号里的表达式，用 break 退出 \n");
    // i = 1; // 不能写在下面的 for 的括号内！原因：赋初始值只执行一次
    i = 1;
    sum = 0;
    for(;;) // 条件表达式2省略时，表示永远为真，此时要在循环中添加退出的条件，否则是死循环！
    {
        if(i > 100)
        {
            break; // 此处的 break 意思是结束循环
        }
        sum += i;
        // printf("i = %d\n", i); // 辅助输出法，检验完毕后可以删除
        i++;
    }
    printf("%d\n", sum);


    printf("\n写法3：等价的 while 循环版本 \n");
    i = 1;
    sum = 0;
    while(i <= 100)
    {
        sum += i;
        i++;
    }
    printf("%d\n", sum);

    return 0;
}