/*原码 补码 反码
正数的原码、补码、反码都是相同的，都是其二进制表示。
负数的原码第一位为1，反码除了符号位外，其余位取反，补码是在反码的基础上加1。
十进制	原码	反码	补码
5	0000 0101	0000 0101	0000 0101
-5	1000 0101	1111 1010	1111 1011
*/
#include<stdio.h>
int main()
{ 
 int a,b;
 float c;
 printf("请输入时速：（km/h）\n");
 scanf("%d",&a);
 printf("预计几小时到达：\n");
 scanf("%d",&b);
 c=a*b;
 printf("你将要行驶的距离为%.1fkm",c);
 return 0;
}